"""
Shared pytest fixtures: a synthetic multi-site cohort with known parameters.

The synthetic generator plants
  * a site effect that is affine per site (random mean shift + random SPD
    covariance),
  * a diagnosis effect along a known unit direction ``w_true`` (ASD subjects are
    shifted by ``diag_effect`` along ``w_true``),
  * a continuous severity score that is a noisy linear function of the
    protected coordinate (NaN for controls),
so that every harmonization / metric routine can be checked against ground
truth without touching real data.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
import pytest


@dataclass
class SyntheticCohort:
    Z: np.ndarray            # (N, d) observed latents
    y_site: np.ndarray       # (N,) int site labels
    y_diag: np.ndarray       # (N,) 0/1 diagnosis
    severity: np.ndarray     # (N,) float, NaN for controls
    w_true: np.ndarray       # (d,) planted diagnosis direction
    site_means: dict         # site -> (d,) mean
    site_covs: dict          # site -> (d, d) covariance
    target_site: int


def _random_spd(rng: np.random.Generator, d: int, scale: float = 1.0) -> np.ndarray:
    A = rng.normal(size=(d, d))
    C = A @ A.T / d + 0.5 * np.eye(d)
    return scale * C


def make_synthetic_cohort(
    n_sites: int = 4,
    sizes: tuple[int, ...] | None = None,
    d: int = 8,
    diag_effect: float = 1.5,
    site_shift: float = 2.0,
    seed: int = 0,
) -> SyntheticCohort:
    rng = np.random.default_rng(seed)
    if sizes is None:
        sizes = tuple(60 for _ in range(n_sites))
    assert len(sizes) == n_sites

    w_true = rng.normal(size=d)
    w_true /= np.linalg.norm(w_true)

    Z_list, site_list, diag_list, sev_list = [], [], [], []
    site_means, site_covs = {}, {}
    for s, n in enumerate(sizes):
        mu = rng.normal(scale=site_shift, size=d)
        cov = _random_spd(rng, d, scale=rng.uniform(0.5, 1.5))
        site_means[s], site_covs[s] = mu, cov
        y = rng.integers(0, 2, size=n)
        base = rng.multivariate_normal(mu, cov, size=n)
        base += np.outer(y * diag_effect, w_true)
        alpha = base @ w_true
        sev = np.where(y == 1, 5.0 + 2.0 * alpha + rng.normal(scale=0.5, size=n), np.nan)
        Z_list.append(base)
        site_list.append(np.full(n, s))
        diag_list.append(y)
        sev_list.append(sev)

    return SyntheticCohort(
        Z=np.vstack(Z_list).astype(np.float64),
        y_site=np.concatenate(site_list).astype(int),
        y_diag=np.concatenate(diag_list).astype(int),
        severity=np.concatenate(sev_list).astype(float),
        w_true=w_true,
        site_means=site_means,
        site_covs=site_covs,
        target_site=0,
    )


@pytest.fixture(scope="session")
def cohort() -> SyntheticCohort:
    """Four balanced synthetic sites, d=8."""
    return make_synthetic_cohort(seed=0)


@pytest.fixture(scope="session")
def small_site_cohort() -> SyntheticCohort:
    """One very small site (n=4 < d) to exercise small-sample guards."""
    return make_synthetic_cohort(n_sites=3, sizes=(80, 40, 4), d=8, seed=1)


@pytest.fixture(scope="session")
def rng() -> np.random.Generator:
    return np.random.default_rng(1234)


def write_synthetic_hdf5(path, cohort: SyntheticCohort, n_rois: int = 12, seed: int = 0):
    """
    Write a tiny HDF5 in the same schema as the real cohorts so the CLI can be
    smoke-tested end to end.  FC vectors are generated by decoding the latent
    through a random linear map into ``n_rois*(n_rois-1)/2`` features.
    """
    import h5py

    rng_ = np.random.default_rng(seed)
    n_feat = n_rois * (n_rois - 1) // 2
    D = rng_.normal(size=(cohort.Z.shape[1], n_feat)) / np.sqrt(cohort.Z.shape[1])
    X = cohort.Z @ D + 0.1 * rng_.normal(size=(cohort.Z.shape[0], n_feat))
    X_half1 = X + 0.05 * rng_.normal(size=X.shape)
    X_half2 = X + 0.05 * rng_.normal(size=X.shape)
    site_names = [f"S{i}" for i in range(len(cohort.site_means))]
    with h5py.File(path, "w") as f:
        f.create_dataset("X", data=X.astype(np.float32))
        f.create_dataset("fc_half1", data=X_half1.astype(np.float32))
        f.create_dataset("fc_half2", data=X_half2.astype(np.float32))
        f.create_dataset("y_site", data=cohort.y_site.astype(np.int32))
        f.create_dataset("y_diagnosis", data=cohort.y_diag.astype(np.int32))
        f.create_dataset("ados_total", data=cohort.severity.astype(np.float32))
        ids = np.array([f"sub{i:04d}" for i in range(len(cohort.y_site))], dtype="S8")
        f.create_dataset("subject_ids", data=ids)
        f.attrs["site_names"] = np.array(site_names, dtype="S")
        f.attrs["n_sites"] = len(site_names)
        f.attrs["n_subjects"] = int(len(cohort.y_site))
        f.attrs["n_rois"] = n_rois
    return path
